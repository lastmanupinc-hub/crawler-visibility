/** robots.ts — generate robots.txt with explicit AI-crawler rules. Bot names from vendor docs. */
export const AI_CRAWLERS = {
  /** Fetch pages for AI search answers (citations). Allowing these is how you show up in answers. */
  search: ["OAI-SearchBot", "ChatGPT-User", "PerplexityBot", "Perplexity-User", "Claude-SearchBot", "Claude-User"],
  /** Collect data for model training. Blocking these does not affect AI search citations. */
  training: ["GPTBot", "ClaudeBot", "Google-Extended", "Applebot-Extended", "CCBot", "meta-externalagent"],
} as const;

export type AiPolicy = "allow-all" | "search-only" | "block-all";

export interface RobotsOptions {
  /** Absolute site URL, used for the Sitemap line. */
  siteUrl: string;
  ai?: AiPolicy;
  /** Paths disallowed for every agent, e.g. ["/app/", "/api/"]. */
  disallow?: string[];
  /** Sitemap path or absolute URL. Default "/sitemap.xml". false to omit. */
  sitemap?: string | false;
}

const cleanPath = (p: string) => {
  if (!/^\/[^\s#]*$/.test(p)) throw new Error(`robots: disallow path must start with "/" and contain no spaces: ${JSON.stringify(p)}`);
  return p;
};

export function buildRobots(o: RobotsOptions): string {
  const policy = o.ai ?? "allow-all";
  if (!["allow-all", "search-only", "block-all"].includes(policy)) throw new Error(`robots: unknown ai policy "${policy}"`);
  const base = new URL(o.siteUrl);
  const dis = (o.disallow ?? []).map(cleanPath);
  const group = (agents: readonly string[], allow: boolean) =>
    [...agents.map((a) => `User-agent: ${a}`), ...(allow ? ["Allow: /", ...dis.map((d) => `Disallow: ${d}`)] : ["Disallow: /"])].join("\n");
  const blocks = [
    "# Generated by crawler-visibility (cv-robots). AI policy: " + policy,
    group(["*"], true),
    group(AI_CRAWLERS.search, policy !== "block-all"),
    group(AI_CRAWLERS.training, policy === "allow-all"),
  ];
  if (o.sitemap !== false) blocks.push(`Sitemap: ${new URL(o.sitemap ?? "/sitemap.xml", base).toString()}`);
  return blocks.join("\n\n") + "\n";
}

export interface RobotsReport { exists: boolean; disallowAll: boolean; aiRules: string[]; sitemaps: string[]; }

/** Parse a robots.txt enough to grade it: which AI bots are named, whether "*" is blocked, sitemap lines. */
export function parseRobots(txt: string | null): RobotsReport {
  if (txt == null) return { exists: false, disallowAll: false, aiRules: [], sitemaps: [] };
  const all = [...AI_CRAWLERS.search, ...AI_CRAWLERS.training].map((s) => s.toLowerCase());
  const lines = txt.split(/\r?\n/).map((l) => l.replace(/#.*/, "").trim()).filter(Boolean);
  const aiRules = new Set<string>(); const sitemaps: string[] = [];
  let agents: string[] = []; let lastWasAgent = false; let disallowAll = false;
  for (const l of lines) {
    const m = l.match(/^([a-z-]+)\s*:\s*(.*)$/i); if (!m) continue;
    const k = m[1].toLowerCase(), v = m[2].trim();
    if (k === "user-agent") { agents = lastWasAgent ? [...agents, v.toLowerCase()] : [v.toLowerCase()]; lastWasAgent = true; if (all.includes(v.toLowerCase())) aiRules.add(v); continue; }
    lastWasAgent = false;
    if (k === "disallow" && v === "/" && agents.includes("*")) disallowAll = true;
    if (k === "sitemap") sitemaps.push(v);
  }
  return { exists: true, disallowAll, aiRules: [...aiRules], sitemaps };
}
